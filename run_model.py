"""
Runs the full Amazon valuation and writes everything to outputs/.

Usage:
    python run_model.py
"""

from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt

from src import model

OUT = Path(__file__).resolve().parent / "outputs"


def fmt_m(x: float) -> str:
    """Format USD millions as $X.XB."""
    return f"${x / 1000:,.1f}B"


def save_charts(proj, sens, price):
    (OUT / "charts").mkdir(parents=True, exist_ok=True)

    fig, ax = plt.subplots(figsize=(8, 4.5))
    ax.bar(proj.index, proj["FCFF"] / 1000, color="#232f3e")
    ax.plot(proj.index, proj["NOPAT"] / 1000, color="#ff9900", marker="o", label="NOPAT")
    ax.set_ylabel("USD billions")
    ax.set_title("Projected Free Cash Flow to Firm vs NOPAT")
    ax.legend()
    for i, v in enumerate(proj["FCFF"] / 1000):
        ax.text(i, v + 1.5, f"{v:.0f}", ha="center")
    fig.tight_layout()
    fig.savefig(OUT / "charts" / "fcff_projection.png", dpi=150)
    plt.close(fig)

    fig, ax = plt.subplots(figsize=(8, 5.5))
    im = ax.imshow(sens.values.astype(float), cmap="RdYlGn", aspect="auto")
    ax.set_xticks(range(len(sens.columns)), sens.columns)
    ax.set_yticks(range(len(sens.index)), sens.index)
    ax.set_xlabel("Terminal growth rate")
    ax.set_ylabel("WACC")
    ax.set_title(f"Value per Share Sensitivity (market price ~${price:.0f})")
    for i in range(len(sens.index)):
        for j in range(len(sens.columns)):
            ax.text(j, i, f"${sens.iat[i, j]:.0f}", ha="center", va="center", fontsize=9)
    fig.colorbar(im, ax=ax, label="Value per share ($)")
    fig.tight_layout()
    fig.savefig(OUT / "charts" / "sensitivity_heatmap.png", dpi=150)
    plt.close(fig)


def main():
    data, assumptions = model.load_inputs()
    base = model.base_year(data)
    w = model.compute_wacc(data, assumptions)
    proj = model.project_fcff(data, assumptions)
    g = assumptions["projection"]["terminal_growth"]
    val = model.dcf_value(proj, w["wacc"], g, base)
    s = assumptions["sensitivity"]
    sens = model.sensitivity(proj, base, s["wacc_range"], s["terminal_growth_range"])
    credit = model.credit_metrics(data)
    price = assumptions["market"]["share_price"]
    implied_g = model.implied_terminal_growth(data, assumptions, w["wacc"], price)
    implied_margin = model.implied_final_year_margin(data, assumptions, w["wacc"], price)

    OUT.mkdir(exist_ok=True)
    proj.to_csv(OUT / "projections.csv", float_format="%.2f")
    sens.to_csv(OUT / "sensitivity.csv", float_format="%.2f")
    save_charts(proj, sens, price)

    proj_md = proj.copy()
    for col in ["Revenue", "EBIT", "NOPAT", "D&A", "Capex", "Change in NWC", "FCFF"]:
        proj_md[col] = proj_md[col].map(lambda x: f"{x:,.0f}")
    for col in ["Growth", "EBIT margin"]:
        proj_md[col] = proj_md[col].map(lambda x: f"{x:.1%}")

    upside = val["value_per_share"] / price - 1
    final_margin = assumptions["projection"]["ebit_margin"][-1]

    lines = [
        "# Amazon (AMZN) Valuation Summary",
        "",
        "Generated by `run_model.py`. Reported figures from Amazon's FY2023 Form 10-K; "
        "market inputs and projections are assumptions (see `config/assumptions.json`). USD millions unless noted.",
        "",
        "## Result",
        "",
        "| | |",
        "|---|---|",
        f"| Enterprise value | {fmt_m(val['enterprise_value'])} |",
        f"| + Cash and marketable securities | {fmt_m(base['cash'])} |",
        f"| - Debt (face value) | {fmt_m(base['debt'])} |",
        f"| Equity value | {fmt_m(val['equity_value'])} |",
        f"| Shares outstanding (millions) | {base['shares']:,} |",
        f"| **Value per share** | **${val['value_per_share']:.2f}** |",
        f"| Market price (assumed) | ${price:.2f} |",
        f"| Implied upside / (downside) | {upside:+.1%} |",
        f"| Terminal value share of EV | {val['terminal_share_of_ev']:.1%} |",
        "",
        "## What the market price implies (reverse DCF)",
        "",
        f"To justify ~${price:.0f} per share with everything else held constant, the model would need either:",
        "",
        f"- a **{implied_margin:.1%} EBIT margin in 2028** instead of the {final_margin:.1%} assumed, or",
        f"- **{implied_g:.1%} perpetual growth** after 2028, which isn't realistic for any company long term.",
        "",
        "Takeaway: the market is pricing in a much longer high-growth runway and a bigger margin shift "
        "(toward higher-margin businesses like AWS and advertising) than a 5-year model with a 3% terminal "
        "rate can capture. The gap is a statement about assumptions, not proof the stock is overvalued.",
        "",
        "## WACC build",
        "",
        "| Component | Value |",
        "|---|---|",
        f"| Risk-free rate | {assumptions['market']['risk_free_rate']:.2%} |",
        f"| Beta | {assumptions['market']['beta']:.2f} |",
        f"| Equity risk premium | {assumptions['market']['equity_risk_premium']:.2%} |",
        f"| Cost of equity (CAPM) | {w['cost_of_equity']:.2%} |",
        f"| Pre-tax cost of debt (interest expense / debt) | {w['pre_tax_cost_of_debt']:.2%} |",
        f"| Effective tax rate (FY2023) | {w['tax_rate']:.2%} |",
        f"| After-tax cost of debt | {w['after_tax_cost_of_debt']:.2%} |",
        f"| Equity weight (market cap {fmt_m(w['market_cap'])}) | {w['weight_equity']:.1%} |",
        f"| Debt weight | {w['weight_debt']:.1%} |",
        f"| **WACC** | **{w['wacc']:.2%}** |",
        "",
        "## Projections",
        "",
        proj_md.to_markdown(),
        "",
        "## Sensitivity: value per share",
        "",
        sens.map(lambda x: f"${x:,.0f}").to_markdown(),
        "",
        "## Credit metrics (FY2023)",
        "",
        "| Metric | Value |",
        "|---|---|",
    ]
    for k, v in credit.items():
        lines.append(f"| {k} | {fmt_m(v) if k == 'EBITDA' else f'{v:.2f}x'} |")
    lines += [
        "",
        "Read: Amazon holds more cash and marketable securities than debt (negative net leverage), covers interest "
        f"{credit['EBIT / interest (interest coverage)']:.1f}x from operating income, and generates "
        f"{credit['DSCR (EBITDA / next-year principal + interest)']:.1f}x the cash needed for next year's scheduled "
        "principal and interest. From a lender's view, this is a very low-risk borrower. "
        "Note: lease liabilities are excluded from debt here; including them would raise leverage meaningfully.",
        "",
        "![FCFF projection](charts/fcff_projection.png)",
        "![Sensitivity](charts/sensitivity_heatmap.png)",
    ]
    (OUT / "valuation_summary.md").write_text("\n".join(lines) + "\n")

    print(f"WACC: {w['wacc']:.2%} | EV: {fmt_m(val['enterprise_value'])} | "
          f"Value/share: ${val['value_per_share']:.2f} vs ${price:.2f} market")
    print(f"Reverse DCF: needs {implied_margin:.1%} 2028E EBIT margin or {implied_g:.1%} terminal growth")
    print(f"Wrote {OUT / 'valuation_summary.md'}")


if __name__ == "__main__":
    main()
